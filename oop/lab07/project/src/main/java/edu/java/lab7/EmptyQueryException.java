package edu.java.lab7;

/**
 * Исключение «пустой поисковый запрос» (ООП, лабораторная работа № 4).
 * Генерируется, когда не задано ни одно условие отбора: выбран вариант
 * «Все читатели», а поле названия книги пустое. Поиск по такому запросу
 * не имеет смысла, так как под его условия попадает весь список выдач.
 *
 * @author Рябов И.А., группа 5315
 * @version 7.0
 */
public class EmptyQueryException extends Exception {

	/** Номер версии класса, используемый при сериализации. */
	private static final long serialVersionUID = 1L;

	/**
	 * Создаёт исключение с сообщением, поясняющим, как задать условия поиска.
	 */
	public EmptyQueryException() {
		super("Выберите читателя или введите название книги для поиска");
	}
}
