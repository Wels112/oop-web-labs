package edu.java.lab5;

/**
 * Исключение «слишком короткое название книги» (ООП, лабораторная работа № 4).
 * Генерируется, когда в поле названия книги введён единственный символ:
 * поиск идёт по вхождению подстроки, поэтому по одному символу отбирается
 * почти весь список выдач. Сообщение содержит введённый текст.
 *
 * @author Рябов И.А., группа 5315
 * @version 5.0
 */
public class ShortNameException extends Exception {

	/** Номер версии класса, используемый при сериализации. */
	private static final long serialVersionUID = 1L;

	/**
	 * Создаёт исключение с сообщением об ошибке и введённым текстом.
	 *
	 * @param name название книги, введённое пользователем
	 */
	public ShortNameException(String name) {
		super("Название книги «" + name
				+ "» слишком короткое: введите не менее двух символов");
	}
}
