package edu.java.lab5;

/**
 * Исключение «слишком короткое название книги».
 * Генерируется при нажатии на кнопку «Поиск», когда в поле названия книги
 * введён единственный символ. Поиск выполняется по вхождению подстроки,
 * поэтому по одному символу отбирается почти весь список выдач и результат
 * оказывается бессмысленным. Сообщение исключения содержит введённый текст.
 *
 * @author Рябов И.А., группа 5315
 * @version 1.0
 */
public class ShortNameException extends Exception {

	/** Номер версии класса, используемый при сериализации. */
	private static final long serialVersionUID = 1L;

	/**
	 * Создаёт исключение и передаёт базовому классу сообщение об ошибке
	 * с указанием введённого пользователем текста.
	 *
	 * @param name название книги, введённое пользователем
	 */
	public ShortNameException(String name) {
		super("Название книги «" + name
				+ "» слишком короткое: введите не менее двух символов");
	}
}
