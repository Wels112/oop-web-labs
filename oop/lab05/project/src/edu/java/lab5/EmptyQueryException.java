package edu.java.lab5;

/**
 * Исключение «пустой поисковый запрос».
 * Генерируется при нажатии на кнопку «Поиск», когда не задано ни одно
 * условие отбора: в выпадающем списке выбран вариант «Все читатели»,
 * а поле названия книги оставлено пустым. Поиск по такому запросу
 * не имеет смысла, так как под его условия попадает весь список выдач.
 *
 * @author Рябов И.А., группа 5315
 * @version 1.0
 */
public class EmptyQueryException extends Exception {

	/** Номер версии класса, используемый при сериализации. */
	private static final long serialVersionUID = 1L;

	/**
	 * Создаёт исключение и передаёт базовому классу сообщение,
	 * поясняющее пользователю, как задать условия поиска.
	 */
	public EmptyQueryException() {
		super("Выберите читателя или введите название книги для поиска");
	}
}
